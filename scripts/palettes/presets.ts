/** Where a preset publishes its blocks, relative to the repository root */
export const paletteFile = (name: string) => `app/assets/css/palettes/${name}.css`

/** The registry key of the palette a member gets without choosing: the base every visitor sees */
export const BASE_PALETTE = 'default'

/**
 * The selector a preset's blocks render under. The base applies wherever no `data-palette` is set,
 * so it never sits beneath a chosen preset; a preset applies under its own `data-palette`. Every
 * selector outranks the `:root` and `.dark` variables Nuxt UI's colours plugin writes at runtime.
 */
export const paletteSelector = (name: string, mode: 'light' | 'dark') => {
    const root = mode === 'dark' ? 'html.dark' : 'html'
    return name === BASE_PALETTE ? `${root}:not([data-palette])` : `${root}[data-palette="${name}"]`
}

/**
 * One family of a hue map: the anchor it takes, what the anchor means in the app, and how the
 * preset publishes it. `scale` redeclares `--color-<family>-<step>`; `slot` redeclares
 * `--ui-color-<slot>-<step>`, which paints `text-<slot>-600` and `bg-<slot>` while the brand
 * family the slot aliases keeps its published value.
 *
 * Every rung takes the anchor's hue. It takes the anchor's chroma too, clamped to the sRGB gamut,
 * unless `chroma` is `ladder`: a family that also paints the app's greys keeps the tint strength of
 * the ladder it walks, so its text and surfaces stay greys in the anchor's hue.
 */
export type Anchor = {hex: string, meaning: string, as: 'scale' | 'slot', ladder: string, chroma?: 'anchor' | 'ladder'}

/** family or Nuxt UI slot → the anchor it takes */
export type HueMap = Record<string, Anchor>

/**
 * A colour-safe preset keeps its meanings apart under protanopia, deuteranopia and tritanopia:
 * `scripts/palettes/render.ts` spreads its meaning faces against the meaning inventory, and
 * `stops` are the colours `RAINBOW` publishes, one per stop in stop order.
 */
export type ColourSafety = {stops: readonly string[]}

export type Preset = {
    name: string
    level: Level
    /** Bumped when the preset is regenerated, so a rerun that changes nothing changes no byte */
    generatedOn: string
    hues: HueMap
    /** Set when the registry badges the preset colour-safe (`PALETTES` in useUserPreferenceValidation.ts) */
    colourSafe?: ColourSafety
    /** The lines of the file's opening comment, between `/*` and the closing marker */
    header: (output: string, generatedOn: string) => string[]
}

