/**
 * The palette presets `scripts/palettes/generate.ts` emits - the data, with no side effects, so a
 * spec can read what the generator solves without running it.
 *
 * The level a preset is generated against is the level `PALETTES` in
 * `app/composables/useUserPreferenceValidation.ts` badges it with and
 * `tests/component/architecture/designSystemContrast.unit.spec.ts` asserts it at;
 * that spec fails when the two lists disagree.
 */

